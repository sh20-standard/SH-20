test('the same keys, signatures and verdicts as the code it replaced, on extreme keys and broken signatures', () => {
  const keys = [1n, 2n, 3n, N - 1n, N - 2n, (N - 1n) / 2n, 1n << 255n, P - 1n].filter((k) => k < N).map(b32);
  for (let i = 0; i < 6; i++) keys.push(sha(`key ${i}`));
  let checked = 0;
  for (const [i, sk] of keys.entries()) {
    const msg = sha(`msg ${i}`);
    const aux = sha(`aux ${i}`);
    const pk = publicKey(sk);
    assert.deepEqual(pk, ref.publicKey(sk));
    const sig = sign(sk, msg, aux);
    assert.deepEqual(sig, ref.sign(sk, msg, aux));
    const cases = [
      [pk, msg, sig],
      [pk, msg, Buffer.concat([sig.subarray(0, 32), b32((BigInt('0x' + sig.subarray(32).toString('hex')) + 1n) % N)])],
      [pk, Buffer.concat([msg.subarray(0, 31), Buffer.from([msg[31] ^ 1])]), sig],
      [Buffer.concat([pk.subarray(0, 31), Buffer.from([pk[31] ^ 1])]), msg, sig], // often not an x on the curve
      [pk, msg, Buffer.concat([b32(P), sig.subarray(32)])], // r = p
      [pk, msg, Buffer.concat([sig.subarray(0, 32), b32(N)])], // s = n
      [pk, msg, Buffer.concat([sig.subarray(0, 32), b32(0n)])], // s = 0
      [b32(P), msg, sig], // a key at the field order
    ];
    for (const [k, m, s] of cases) {
      assert.equal(verify(k, m, s), ref.verify(k, m, s));
      checked++;
    }
    assert.ok(verify(pk, msg, sig));
  }
  assert.equal(checked, keys.length * 8);
});
